export type Copy = (typeof bundles)["en"];

export function copyFor(language: Language): Copy {
  return bundles[language] as Copy;
}

export function useCopy(): Copy & { language: Language; intl: string; categoryName: (id: string) => string } {
  const language = useLanguage();
  const bundle = copyFor(language);
  return {
    ...bundle,
    language,
    intl: intlLocale(language),
    categoryName: (id: string) => categoryLabel(id, language),
  };
}
